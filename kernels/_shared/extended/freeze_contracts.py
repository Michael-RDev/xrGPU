"""Freeze local upstream tensor contracts into a JSON-free native validation table."""
# SPDX-License-Identifier: Apache-2.0
import json
from pathlib import Path
from kernels import catalog as native_catalog, provenance

ROOT = Path(__file__).resolve().parents[3]
DTYPES = ["float32", "float16", "int32", "uint32", "int16", "int8", "uint8", "int64", "bool"]


def freeze(root=ROOT, *, check=False):
    root = Path(root)
    catalog = native_catalog.load(root / "kernels")
    records = []
    rows = []
    for entry in catalog["entries"]:
        value = json.loads(native_catalog.regular(root / "kernels", entry["contract"]).read_text())
        original = provenance.document(entry["id"], "contract", root=root / "kernels/_provenance")
        source = entry["provenance"]
        digest = source["files"][source["contract"]]
        record = dict(id=entry["id"], revision=source["revision"], contract_sha256=digest,
            inputs=value.get("inputs", {}), outputs=value.get("outputs", {}),
            type_constraints=value.get("type_constraints", {}),
            attributes=value.get("attributes", {}),
            attribute_constraints=value.get("attribute_constraints", {}))
        records.append(record)
        for side in ("inputs", "outputs"):
            for name in original.get(side, {}):
                tensor = record[side][name]
                variable = tensor["dtype"]
                allowed = record["type_constraints"].get(variable, [variable])
                mask = sum(1 << DTYPES.index(t) for t in allowed)
                rank = tensor.get("rank", -1)
                if not isinstance(rank, int):
                    rank = -1
                fields = [entry["id"], name, variable]
                rows.append("{" + ",".join(json.dumps(x) for x in fields) +
                    "," + str(mask) + "," + str(rank) + "," +
                    str(tensor.get("optional", False)).lower() + "," +
                    str(side == "outputs").lower() + "},\n")
    out = root / "kernels/_shared/extended"
    content = dict(schema_version=1, upstream_catalog_sha256=catalog["upstream_catalog_sha256"], operations=records)
    serialized = json.dumps(content, sort_keys=True, indent=2) + "\n"
    header = """// SPDX-License-Identifier: Apache-2.0
// Generated by freeze_contracts.py from checksummed local upstream metadata.
#pragma once
namespace xrgpu::operators::extended::detail {
struct TensorContract {const char* operation;const char* name;const char* variable;uint32_t dtype_mask;int rank;bool optional;bool output;};
inline constexpr TensorContract kTensorContracts[]={
""" + "".join(rows) + "};\n}\n"
    for name, text in (("contracts.json", serialized), ("contract_data.h", header)):
        path = out / name
        if check:
            if path.read_text() != text:
                raise ValueError("Generated native contract drift: " + name)
        else:
            path.write_text(text)
    return len(records)


if __name__ == "__main__":
    print(freeze())
